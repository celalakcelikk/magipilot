// `Magipilot: Use for Commit Messages` (docs/plans/phase-2.md D2). Copilot Chat generates commit
// messages with the *utility* models; with default settings it uses its own service, so the
// staged diff leaves the machine (Faz 0 Q3). The command routes both utility settings to a
// Magipilot model in the user settings and then checks that the routing is really effective.
import * as vscode from 'vscode';
import {
  migratedUtilityValue,
  overridingScope,
  vendorOf,
  type ChatModelDescriptor,
} from './models';

export const COMMIT_ROUTING_COMMAND = 'magipilot.useForCommitMessages';
const KEYS = ['utilityModel', 'utilitySmallModel'] as const;

export interface CommitRoutingResult {
  /** `<vendor>/<id>`, or undefined when nothing was written. */
  value?: string;
  /** True when both settings now resolve to `value`. */
  effective: boolean;
  /** Settings that a workspace (folder) value overrides, e.g. `chat.utilitySmallModel (Workspace)`. */
  overrides: string[];
}

export async function useForCommitMessages(
  models: readonly ChatModelDescriptor[],
  requestedId?: string,
): Promise<CommitRoutingResult> {
  if (models.length === 0) {
    void vscode.window.showWarningMessage(
      'Magipilot: no chat models are available. Add model ids to "magipilot.chat.claude.models" or "magipilot.chat.codex.models" (and make sure the CLI is installed).',
    );
    return { effective: false, overrides: [] };
  }
  let model = requestedId ? models.find((m) => m.id === requestedId) : undefined;
  if (!model && !requestedId) {
    const pick = await vscode.window.showQuickPick(
      models.map((m) => ({ label: m.name, description: m.id, model: m })),
      { title: 'Magipilot: model for commit messages (Copilot utility models)' },
    );
    model = pick?.model;
  }
  if (!model) return { effective: false, overrides: [] };

  // Each CLI's models have their own vendor (phase-4-context.md G1, G2).
  const value = `${vendorOf(model.backend)}/${model.id}`;
  const chat = vscode.workspace.getConfiguration('chat');
  for (const key of KEYS) await chat.update(key, value, vscode.ConfigurationTarget.Global);

  // A workspace or folder value wins over the user value (plan review P2-R003).
  const resource = vscode.window.activeTextEditor?.document.uri;
  const effectiveConfig = vscode.workspace.getConfiguration('chat', resource);
  const overrides: string[] = [];
  for (const key of KEYS) {
    const scope = overridingScope(effectiveConfig.inspect<string>(key), value);
    if (scope) overrides.push(`chat.${key} (${scope})`);
  }
  const effective = overrides.length === 0;
  if (effective) {
    void vscode.window.showInformationMessage(
      `Magipilot: commit messages will be generated by ${model.name}.`,
    );
  } else {
    void vscode.window.showWarningMessage(
      `Magipilot: the user settings were updated, but ${overrides.join(', ')} override them, so commit messages are not routed to ${model.name}. Remove or change those settings.`,
    );
  }
  return { value, effective, overrides };
}

/**
 * At activation (G2): a user-scope utility setting with an old Codex value is rewritten to the
 * new identifier, which keeps commit messages on the model the user chose; a workspace or folder
 * value of that form is only reported, since Magipilot never writes workspace settings.
 */
export async function migrateUtilityModels(log: {
  info(message: string, meta?: object): void;
  warn(message: string, meta?: object): void;
}): Promise<{ rewritten: string[]; reported: string[] }> {
  const rewritten: string[] = [];
  const reported: string[] = [];
  const chat = vscode.workspace.getConfiguration('chat');
  for (const key of KEYS) {
    const values = chat.inspect<string>(key);
    const updated = migratedUtilityValue(values?.globalValue);
    if (updated !== undefined) {
      await chat.update(key, updated, vscode.ConfigurationTarget.Global);
      rewritten.push(`chat.${key}`);
    }
    if (migratedUtilityValue(values?.workspaceValue) !== undefined) {
      reported.push(`chat.${key} (Workspace)`);
    }
    // A single-folder workspace's folder settings are its workspace settings (reported above).
    const folders = vscode.workspace.workspaceFile ? (vscode.workspace.workspaceFolders ?? []) : [];
    for (const folder of folders) {
      const folderValue = vscode.workspace
        .getConfiguration('chat', folder.uri)
        .inspect<string>(key)?.workspaceFolderValue;
      if (migratedUtilityValue(folderValue) !== undefined) {
        reported.push(`chat.${key} (Workspace Folder ${folder.name})`);
      }
    }
  }
  if (rewritten.length > 0) {
    log.info('utility models migrated', { settings: rewritten.length });
    void vscode.window.showInformationMessage(
      `Magipilot: Codex models now have their own group, "Codex (CLI)". ${rewritten.join(' and ')} now name the same model by its new id, so commit messages keep using it.`,
    );
  }
  if (reported.length > 0) {
    log.warn('utility models with an old id', { settings: reported.length });
    void vscode.window.showWarningMessage(
      `Magipilot: ${reported.join(', ')} name a Codex model by its old id (magipilot/codex-cli.…), so commit messages do not use it. Change it to magipilot-codex/codex-cli.…, or run "Magipilot: Use for Commit Messages".`,
    );
  }
  return { rewritten, reported };
}
